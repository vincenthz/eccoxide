//! SM2 elliptic curve parameters
//!
//! The recommended 256-bit prime-field curve from the Chinese SM2 standard
//! (GB/T 32918 / GM/T 0003). It is a short Weierstrass curve
//! `y^2 = x^3 + a*x + b` over the prime field `Fp` with
//! `p = 2^256 - 2^224 - 2^96 + 2^64 - 1`, cofactor 1, and `a = p - 3` (so the
//! `a == -3` point-arithmetic optimisation applies, exactly like the NIST/SEC2
//! `r1` curves).
//!
//! Big-endian bytes and big-endian 64-bit limb forms are provided, matching
//! the other curve parameter modules.

