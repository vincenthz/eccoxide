//! Jubjub curve parameters
//!
//! Jubjub is the twisted Edwards curve `-x^2 + y^2 = 1 + d*x^2*y^2` defined over
//! the BLS12-381 scalar field `Fr` (so its coordinates are
//! [`bls12_381::Scalar`](crate::curve::bls12_381::Scalar) elements). It has
//! cofactor 8; the prime-order subgroup has 252-bit order `r`, which is the
//! order of the Jubjub scalar field [`Scalar`](crate::curve::jubjub::Scalar).
//!
//! All curve constants are big-endian 32-byte encodings of `Fr` elements.

